import { expect, test } from "@playwright/test"

for (const width of [390, 1280]) {
  for (const colorScheme of ["light", "dark"] as const) {
    test(`Filter, gespeicherte Ansicht und Fokus bei ${width}px in ${colorScheme}`, async ({ page }) => {
      await page.setViewportSize({ width, height: 844 })
      await page.emulateMedia({ colorScheme })
      await page.goto("/")
      await expect(page.getByRole("heading", { name: "Prüfstationen" })).toBeVisible()
      const trigger = page.getByRole("button", { name: "Ansicht speichern" })
      await expect(trigger).toBeDisabled()
      await page.getByLabel("Status", { exact: true }).selectOption("In Prüfung")
      await expect(page.getByRole("row")).toHaveCount(3)
      await trigger.press("Enter")
      const dialog = page.getByRole("dialog")
      const field = dialog.getByRole("textbox")
      await expect(field).toBeFocused()
      await field.press("Enter")
      await expect(dialog.getByRole("alert")).toHaveText("Gib einen Namen ein.")
      await field.fill("Meine Filter")
      await field.press("Enter")
      await expect(page.getByRole("status")).toHaveText("Gespeichert: Meine Filter")
      await expect(trigger).toBeFocused()
      await page.reload()
      await page.getByLabel("Gespeicherte Ansicht").selectOption("Meine Filter")
      await expect(page.getByLabel("Status", { exact: true })).toHaveValue("In Prüfung")
      await page.getByRole("searchbox").fill("keine passende station")
      await expect(page.getByText("Keine Treffer")).toBeVisible()
      await trigger.press("Enter")
      await field.press("Escape")
      await expect(dialog).toBeHidden()
      await expect(trigger).toBeFocused()
      await page.getByRole("link", { name: "Wartungsaufträge" }).click()
      await expect(page.getByRole("row")).toHaveCount(4)
      await page.getByRole("link", { name: "Komponenten" }).click()
      await expect(page.getByRole("table", { name: "Button-Zustände" })).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
      await expect(page.locator("html")).toHaveCSS("color-scheme", colorScheme)
      await page.getByLabel("Farbschema").selectOption(colorScheme === "dark" ? "light" : "dark")
      await expect(page.locator("html")).toHaveCSS("color-scheme", colorScheme === "dark" ? "light" : "dark")
    })
  }
}
